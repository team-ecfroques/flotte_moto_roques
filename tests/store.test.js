import test from 'node:test';
import assert from 'node:assert/strict';
import { localStore } from '../public/assets/js/store.js';
import { sortedFaults, faultIdentity } from '../public/assets/js/model.js';
test('ajout, doublon, changement de statut, rechargement et suppression',async () => {
  const memory = new Map();
  globalThis.localStorage = {getItem:key => memory.get(key) ?? null,setItem:(key,value) => memory.set(key,value)};
  const listeners = {};
  globalThis.window = {addEventListener:(name,callback) => {listeners[name] = callback;}};
  let data;
  const store = localStore(value => {data = value;});
  await store.rememberFault(' Béquille cassée ');
  await store.rememberFault('béquille cassée');
  let faults;
  localStore(() => {},value => {faults = value;});
  assert.deepEqual(faults,['Béquille cassée']);
  assert.equal(Object.keys(data).length,3);
  const moto = {plate:'AA-123-BB',model:'Test',status:'available',mileage:100,service:0};
  await store.save(moto.plate,moto,true);
  assert.equal(Object.keys(data).length,4);
  await assert.rejects(store.save(moto.plate,moto,true),/existe déjà/);
  await assert.rejects(store.save(moto.plate,{plate:'ZZ-999-ZZ'}),/immatriculation/);
  await assert.rejects(store.save(moto.plate,{mileage:-10}),/kilométrage/);
  await store.save(moto.plate,{status:'repair',fault:'Béquille cassée'});
  assert.equal(data[moto.plate].mileage,100);
  assert.equal(data[moto.plate].status,'repair');
  let reloaded;
  localStore(value => {reloaded = value;});
  assert.equal(reloaded[moto.plate].status,'repair');
  assert.equal(reloaded[moto.plate].fault,'Béquille cassée');
  await store.removeFault('Béquille cassée');
  await store.removeFault('Frein');
  let hidden;
  localStore(value => {reloaded = value;},(values,excluded) => {faults = values; hidden = excluded;});
  assert.equal(reloaded[moto.plate].fault,'Béquille cassée');
  assert.ok(!sortedFaults(faults,hidden).some(value => ['béquille cassée','frein'].includes(faultIdentity(value))));
  await store.rememberFault('Béquille cassée');
  localStore(() => {},(values,excluded) => {faults = values; hidden = excluded;});
  assert.ok(sortedFaults(faults,hidden).includes('Béquille cassée'));
  assert.ok(!sortedFaults(faults,hidden).some(value => faultIdentity(value) === 'frein'));
  await store.save(moto.plate,{status:'available',fault:null});
  assert.equal(data[moto.plate].fault,null);
  await store.remove(moto.plate);
  assert.equal(data[moto.plate],undefined);
  await assert.rejects(store.save(moto.plate,{status:'available'}),/supprimée/);
  for (const id of Object.keys(data)) await store.remove(id);
  localStore(value => {reloaded = value;});
  assert.deepEqual(reloaded,{});
  localStore(() => {},value => {faults = value;});
  assert.deepEqual(faults,['Béquille cassée']);
  listeners.storage({key:'ecf-moto-demo-v1'});
  assert.deepEqual(reloaded,{});
});
